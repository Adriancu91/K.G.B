//! Local identity (Etapa 1, step 1.6; decision D-025; Master Plan §7).
//!
//! - **Device identity:** an Ed25519 key pair generated on this PC the first
//!   time K.G.B. runs. The secret key never leaves the PC and is never part of
//!   the installer. On disk it is sealed with Windows DPAPI for the current
//!   Windows user, so copying the file to another user or PC does not reveal it.
//!   The same key type is used by iroh, so Etapa 6 can reuse it for pairing.
//! - **Owner:** the local person who created the workspace (`core.identity`).
//!   Other users, roles and invitations come with Etapa 6.
//!
//! No cryptography is implemented here: keys come from `ed25519-dalek`,
//! randomness from the OS (`getrandom`), sealing from DPAPI.

use std::fs;
use std::path::{Path, PathBuf};

use ed25519_dalek::{Signature, Signer, SigningKey, Verifier, VerifyingKey};
use kgb_store::fsutil::write_atomic;
use kgb_store::{Fields, Store, Write};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use uuid::Uuid;
use zeroize::Zeroizing;

use crate::error::{CoreError, CoreResult};
use crate::workspace::{now_ms, validate_name};

pub const DEVICE_KEY_FILE: &str = "device.key";
const DEVICE_KEY_FORMAT: u32 = 1;
/// Extra DPAPI entropy: binds the sealed blob to this purpose.
const DPAPI_ENTROPY: &[u8] = b"K.G.B. device key v1";

pub const IDENTITY_COLLECTION: &str = "core.identity";
pub const OWNER_ID: Uuid = Uuid::from_u128(1);
pub const DEVICES_COLLECTION: &str = "core.devices";

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct KeyFile {
    format: u32,
    protection: String,
    public: String,
    sealed: String,
}

/// This PC's identity. The secret key is held in memory only while K.G.B. runs
/// and is wiped on drop (ed25519-dalek zeroizes `SigningKey`).
pub struct DeviceIdentity {
    key: SigningKey,
    path: PathBuf,
    created: bool,
}

impl std::fmt::Debug for DeviceIdentity {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // Never print the secret key.
        f.debug_struct("DeviceIdentity")
            .field("public", &self.public_hex())
            .finish()
    }
}

impl DeviceIdentity {
    /// Loads `<dir>/device.key`, or generates and seals a new key on first run.
    pub fn load_or_create(dir: &Path) -> CoreResult<DeviceIdentity> {
        let path = dir.join(DEVICE_KEY_FILE);
        match fs::read(&path) {
            Ok(bytes) => Ok(DeviceIdentity {
                key: unseal_file(&path, &bytes)?,
                path,
                created: false,
            }),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
                fs::create_dir_all(dir)?;
                let mut secret = Zeroizing::new([0u8; 32]);
                getrandom::fill(secret.as_mut())
                    .map_err(|e| CoreError::invalid("generatorul de numere aleatoare", e.to_string()))?;
                let key = SigningKey::from_bytes(&secret);
                let sealed = dpapi::protect(secret.as_ref(), DPAPI_ENTROPY)?;
                let file = KeyFile {
                    format: DEVICE_KEY_FORMAT,
                    protection: dpapi::NAME.into(),
                    public: hex(key.verifying_key().as_bytes()),
                    sealed: hex(&sealed),
                };
                write_atomic(&path, &serde_json::to_vec_pretty(&file).expect("key file serialises"))?;
                Ok(DeviceIdentity {
                    key,
                    path,
                    created: true,
                })
            }
            Err(e) => Err(e.into()),
        }
    }

    pub fn public_key(&self) -> VerifyingKey {
        self.key.verifying_key()
    }
    pub fn public_hex(&self) -> String {
        hex(self.key.verifying_key().as_bytes())
    }
    /// Short, human-comparable fingerprint, e.g. `3F2A-91C0-77DE-0B14`.
    pub fn fingerprint(&self) -> String {
        fingerprint(&self.public_key())
    }
    pub fn path(&self) -> &Path {
        &self.path
    }
    /// True if the key was generated by this call (first run on this PC).
    pub fn created(&self) -> bool {
        self.created
    }
    /// The secret key, for the network layer only (Etapa 6, step 6.5): iroh
    /// authenticates every connection with this same key, so a connection
    /// proves the device identity that the signed registry lists.
    pub fn secret_bytes(&self) -> Zeroizing<[u8; 32]> {
        Zeroizing::new(self.key.to_bytes())
    }

    pub fn sign(&self, msg: &[u8]) -> Signature {
        self.key.sign(msg)
    }
}

pub fn verify(public: &VerifyingKey, msg: &[u8], sig: &Signature) -> bool {
    public.verify(msg, sig).is_ok()
}

pub fn fingerprint(public: &VerifyingKey) -> String {
    let h = blake3::hash(public.as_bytes());
    let x = hex(&h.as_bytes()[..8]).to_uppercase();
    format!("{}-{}-{}-{}", &x[0..4], &x[4..8], &x[8..12], &x[12..16])
}

fn corrupt(path: &Path, detail: impl Into<String>) -> CoreError {
    CoreError::WorkspaceManifestCorrupt {
        path: path.into(),
        detail: detail.into(),
    }
}

fn unseal_file(path: &Path, bytes: &[u8]) -> CoreResult<SigningKey> {
    let f: KeyFile = serde_json::from_slice(bytes).map_err(|e| corrupt(path, e.to_string()))?;
    if f.format != DEVICE_KEY_FORMAT || f.protection != dpapi::NAME {
        return Err(corrupt(
            path,
            format!("format {} / protecție {} necunoscute", f.format, f.protection),
        ));
    }
    let sealed = unhex(&f.sealed).ok_or_else(|| corrupt(path, "câmpul sealed nu este hex"))?;
    let secret = Zeroizing::new(dpapi::unprotect(&sealed, DPAPI_ENTROPY).map_err(|e| corrupt(path, e.to_string()))?);
    let secret: &[u8; 32] = secret
        .as_slice()
        .try_into()
        .map_err(|_| corrupt(path, "cheia nu are 32 de octeți"))?;
    let key = SigningKey::from_bytes(secret);
    if hex(key.verifying_key().as_bytes()) != f.public {
        return Err(corrupt(path, "cheia publică nu corespunde cheii secrete"));
    }
    Ok(key)
}

pub fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

pub fn unhex(s: &str) -> Option<Vec<u8>> {
    if !s.len().is_multiple_of(2) {
        return None;
    }
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(s.get(i..i + 2)?, 16).ok())
        .collect()
}

/// Owner of the workspace (the local person).
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct Owner {
    pub display_name: String,
    pub created_ms: u64,
    pub version: u64,
}

pub fn owner(store: &Store) -> CoreResult<Option<Owner>> {
    Ok(store.get(IDENTITY_COLLECTION, OWNER_ID)?.map(|r| Owner {
        display_name: r
            .fields
            .get("display_name")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string(),
        created_ms: r.fields.get("created_ms").and_then(Value::as_u64).unwrap_or_default(),
        version: r.version,
    }))
}

/// Creates or renames the owner. `expected_version` 0 = create.
pub fn set_owner(store: &mut Store, display_name: &str, expected_version: u64) -> CoreResult<u64> {
    let name = validate_name("numele proprietarului", display_name)?;
    let created = match owner(store)? {
        Some(o) => o.created_ms,
        None => now_ms(),
    };
    let mut f = Fields::new();
    f.insert("display_name".into(), Value::String(name));
    f.insert("created_ms".into(), Value::from(created));
    Ok(store.write(vec![
        Write::put(IDENTITY_COLLECTION, OWNER_ID, f).expect(expected_version),
    ])?[0])
}

/// Device states from Master Plan §7.2.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum DeviceStatus {
    Pending,
    Approved,
    Suspended,
    Revoked,
}

/// Records this PC in the workspace as an approved device (it created or
/// opened the workspace locally). Idempotent. Returns the record id.
pub fn register_this_device(store: &mut Store, dev: &DeviceIdentity, label: &str) -> CoreResult<Uuid> {
    let id = Uuid::new_v5(&Uuid::NAMESPACE_OID, dev.public_key().as_bytes());
    if store.get(DEVICES_COLLECTION, id)?.is_some() {
        return Ok(id);
    }
    let mut f = Fields::new();
    f.insert("public_key".into(), Value::String(dev.public_hex()));
    f.insert("fingerprint".into(), Value::String(dev.fingerprint()));
    f.insert(
        "label".into(),
        Value::String(validate_name("numele dispozitivului", label)?),
    );
    f.insert(
        "status".into(),
        serde_json::to_value(DeviceStatus::Approved).expect("status serialises"),
    );
    f.insert(
        "history".into(),
        serde_json::json!([{"ts_ms": now_ms(), "status": "approved", "reason": "dispozitivul local al proprietarului"}]),
    );
    store.write(vec![Write::put(DEVICES_COLLECTION, id, f).expect(0)])?;
    Ok(id)
}

#[cfg(windows)]
mod dpapi {
    //! Windows Data Protection API, scope: current Windows user.
    use std::io;

    use windows_sys::Win32::Foundation::{HLOCAL, LocalFree};
    use windows_sys::Win32::Security::Cryptography::{
        CRYPT_INTEGER_BLOB, CRYPTPROTECT_UI_FORBIDDEN, CryptProtectData, CryptUnprotectData,
    };

    pub const NAME: &str = "dpapi-user";

    fn blob(b: &[u8]) -> CRYPT_INTEGER_BLOB {
        CRYPT_INTEGER_BLOB {
            cbData: b.len() as u32,
            pbData: b.as_ptr() as *mut u8,
        }
    }

    fn take(out: CRYPT_INTEGER_BLOB) -> Vec<u8> {
        // SAFETY: on success DPAPI returns a LocalAlloc'ed buffer of cbData bytes
        // that we copy and then free exactly once.
        unsafe {
            let v = std::slice::from_raw_parts(out.pbData, out.cbData as usize).to_vec();
            LocalFree(out.pbData as HLOCAL);
            v
        }
    }

    pub fn protect(data: &[u8], entropy: &[u8]) -> io::Result<Vec<u8>> {
        let input = blob(data);
        let ent = blob(entropy);
        let mut out = CRYPT_INTEGER_BLOB {
            cbData: 0,
            pbData: std::ptr::null_mut(),
        };
        // SAFETY: all pointers refer to live buffers for the duration of the call.
        let ok = unsafe {
            CryptProtectData(
                &input,
                std::ptr::null(),
                &ent,
                std::ptr::null(),
                std::ptr::null(),
                CRYPTPROTECT_UI_FORBIDDEN,
                &mut out,
            )
        };
        if ok == 0 {
            return Err(io::Error::last_os_error());
        }
        Ok(take(out))
    }

    pub fn unprotect(data: &[u8], entropy: &[u8]) -> io::Result<Vec<u8>> {
        let input = blob(data);
        let ent = blob(entropy);
        let mut out = CRYPT_INTEGER_BLOB {
            cbData: 0,
            pbData: std::ptr::null_mut(),
        };
        // SAFETY: as above.
        let ok = unsafe {
            CryptUnprotectData(
                &input,
                std::ptr::null_mut(),
                &ent,
                std::ptr::null(),
                std::ptr::null(),
                CRYPTPROTECT_UI_FORBIDDEN,
                &mut out,
            )
        };
        if ok == 0 {
            return Err(io::Error::last_os_error());
        }
        Ok(take(out))
    }
}

#[cfg(not(windows))]
mod dpapi {
    //! K.G.B. targets Windows first (D-002). macOS will use the Keychain.
    use std::io;
    pub const NAME: &str = "unsupported";
    pub fn protect(_: &[u8], _: &[u8]) -> io::Result<Vec<u8>> {
        Err(io::Error::other("protecția cheii este implementată doar pe Windows"))
    }
    pub fn unprotect(_: &[u8], _: &[u8]) -> io::Result<Vec<u8>> {
        Err(io::Error::other("protecția cheii este implementată doar pe Windows"))
    }
}
